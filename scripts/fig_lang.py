RESULTS_DIR = os.path.join("outputs", "results")
EXTRACTOR_LABELS = {"ctranspath": "CTransPath", "resnet50": "ResNet-50", "uni": "UNI"}
STRATEGY_LABELS = {"none": "none", "oversample": "oversample", "smote": "SMOTE"}
AGG_COLOURS = {"patch_level": "#2ca02c", "mean_pool": "#7f7f7f", "abmil": "#1f77b4", "clam_sb": "#ff7f0e"}
AGG_LABELS = {
    "tr": {"patch_level": "Yama düzeyi", "mean_pool": "Ort. havuzlama", "abmil": "ABMIL", "clam_sb": "CLAM-SB"},
    "en": {"patch_level": "Patch-level", "mean_pool": "Mean pooling", "abmil": "ABMIL", "clam_sb": "CLAM-SB"},
}


def lang_args(name, parser=None):
    parser = parser or argparse.ArgumentParser()
    parser.add_argument("--lang", choices=("tr", "en"), default="en")
    parser.add_argument("--out", default=None, help="default: outputs/figures/<lang>/<name>")
    args = parser.parse_args()
    args.out = args.out or os.path.join("outputs", "figures", args.lang, name)
    return args


def agg_styles(lang):
    return {key: (AGG_LABELS[lang][key], colour) for key, colour in AGG_COLOURS.items()}


def load_summary(macenko_only=False):
    df = pd.read_csv(os.path.join(RESULTS_DIR, "summary_metrics.csv"))
    df["macenko"] = df["strategy"].str.startswith("stainnorm_")
    df["strat"] = df["strategy"].str.removeprefix("stainnorm_")
    return df[df["macenko"]].copy() if macenko_only else df


def load_folds(config_name):
    return pd.read_csv(os.path.join(RESULTS_DIR, f"{config_name}_folds.csv"))


def prevalence(df):
    first = df.iloc[0]
    return (first.tp + first.fn) / (first.tp + first.fn + first.tn + first.fp)


def legend_handles(styles):
    return [Line2D([0], [0], marker="o", color="w", markerfacecolor=colour, markersize=8, label=label)
            for label, colour in styles]


def save(fig, path):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fig.savefig(path, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print("Saved:", path)


def sample_patches(patient_dir, coords_path, n, rng):
    with h5py.File(coords_path, "r") as f:
        coords = f["coords"][:]
        level = int(f.attrs["target_level"])
        size = int(f.attrs["patch_size"])
    idx = np.sort(rng.choice(len(coords), size=min(n, len(coords)), replace=False))
    with open_wsi(patient_dir) as slide:
        return [slide.read_region((int(x), int(y)), level, (size, size)).convert("RGB") for x, y in coords[idx]]


def bold(cells):
    return [f"\\textbf{{{c}}}" for c in cells]


def latex_table(generator, caption, label, colspec, header, rows, small=False):
    # X-type (C) columns stretch to the full width; plain specs keep natural widths so CI cells never wrap.
    if "C" in colspec:
        begin, end = f"\\begin{{tabularx}}{{\\fulllength}}{{{colspec}}}", "\\end{tabularx}"
    else:
        begin, end = f"\\centering\\begin{{tabular}}{{{colspec}}}", "\\end{tabular}"
    lines = [f"% Generated by {generator}; do not edit by hand.", "\\begin{table}[H]",
             f"\\caption{{{caption}\\label{{{label}}}}}", "\\begin{adjustwidth}{-\\extralength}{0cm}"]
    lines += ["\\footnotesize"] if small else []
    lines += [begin, "\\toprule", " & ".join(header) + "\\\\", "\\midrule"]
    lines += [row if isinstance(row, str) else " & ".join(row) + "\\\\" for row in rows]
    lines += ["\\bottomrule", end, "\\end{adjustwidth}", "\\end{table}", ""]
    return "\n".join(lines)


def write(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("Saved:", path)


def number(x, digits, lang):
    text = f"{x:.{digits}f}"
    return text.replace(".", ",") if lang == "tr" else text


def config_label(row, lang):
    sep = " / " if lang == "tr" else "/"
    return sep.join((AGG_LABELS[lang][row.aggregator], EXTRACTOR_LABELS[row.extractor],
                     STRATEGY_LABELS[row.strat]))


def with_ci(row, metric, digits, lang):
    lo, hi = (number(getattr(row, f"{metric}_ci_{b}"), 2, lang) for b in ("lower", "upper"))
    value = number(getattr(row, metric), digits, lang)
    return f"{value} [{lo}--{hi}]" if lang == "en" else f"{value} [{lo}–{hi}]"
